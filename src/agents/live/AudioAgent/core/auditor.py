import time
import os
import requests
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors


class Auditor:
    def __init__(self):
        pass

    def scan_site(self, url):
        """Performs a passive technical audit."""
        print(f"      🩺 Scanning {url}...")
        results = {
            "load_time": 0.0,
            "ssl": False,
            "security_headers": False,
            "server": "Unknown",
            "score": "F",
        }

        try:
            start = time.time()
            # Fake user agent to avoid instant blocking
            headers = {
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36"
            }
            response = requests.get(url, headers=headers, timeout=10)
            results["load_time"] = round(time.time() - start, 2)
            results["ssl"] = url.startswith("https")
            results["server"] = response.headers.get("Server", "Hidden")

            # Security Headers Check
            sec_headers = [
                "Strict-Transport-Security",
                "Content-Security-Policy",
                "X-Frame-Options",
            ]
            present = [h for h in sec_headers if h in response.headers]
            results["security_headers"] = len(present) > 0

            # Simple Scoring Not Arbitrary
            score_val = 100
            if results["load_time"] > 2.0:
                score_val -= 20
            if results["load_time"] > 4.0:
                score_val -= 20
            if not results["ssl"]:
                score_val -= 30
            if not results["security_headers"]:
                score_val -= 10

            if score_val >= 90:
                results["score"] = "A"
            elif score_val >= 80:
                results["score"] = "B"
            elif score_val >= 70:
                results["score"] = "C"
            elif score_val >= 60:
                results["score"] = "D"
            else:
                results["score"] = "F"

        except Exception as e:
            print(f"      ⚠️ Scan failed: {e}")
            results["score"] = "N/A"

        return results

    def generate_report(self, company, data, output_path):
        """Generates a professional PDF audit report."""
        c = canvas.Canvas(output_path, pagesize=letter)
        w, h = letter

        # Header
        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 24)
        c.drawString(50, h - 50, f"INFRASTRUCTURE AUDIT: {company.upper()}")

        c.setFont("Helvetica", 12)
        c.setFillColor(colors.gray)
        c.drawString(
            50,
            h - 70,
            f"Generated by SGM Audio Architect | {time.strftime('%Y-%m-%d')}",
        )

        c.line(50, h - 80, w - 50, h - 80)

        # Summary Box
        c.setFillColor(colors.lightgrey)
        c.rect(50, h - 250, w - 100, 150, fill=1)

        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 60)
        score = data.get("score", "N/A")
        # Color coding score
        if score in ["A", "B"]:
            c.setFillColor(colors.green)
        elif score in ["C"]:
            c.setFillColor(colors.orange)
        else:
            c.setFillColor(colors.red)

        c.drawString(80, h - 180, score)

        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 14)
        c.drawString(200, h - 140, "OVERALL HEALTH SCORE")

        c.setFont("Helvetica", 12)
        c.drawString(
            200, h - 160, "Based on Performance, Security, and Asset Delivery."
        )

        # Metrics
        y = h - 300
        c.setFont("Helvetica-Bold", 18)
        c.drawString(50, y, "TECHNICAL FINDINGS")
        y -= 30

        metrics = [
            ("Load Time (TTFB)", f"{data['load_time']}s", "Target: < 1.5s"),
            (
                "SSL / Encryption",
                "Active" if data["ssl"] else "MISSING",
                "Essential for Client Trust",
            ),
            ("Server Architecture", data["server"], "Legacy indicators detected"),
            (
                "Security Policies",
                "Detected" if data["security_headers"] else "MISSING",
                "Vulnerable to XSS/Injection",
            ),
        ]

        c.setFont("Helvetica", 12)
        for label, val, desc in metrics:
            c.drawString(50, y, f"{label}:")
            c.drawString(250, y, val)
            c.setFillColor(colors.gray)
            c.setFont("Helvetica-Oblique", 10)
            c.drawString(400, y, desc)
            c.setFillColor(colors.black)
            c.setFont("Helvetica", 12)
            y -= 30

        # Footer / Pitch
        c.line(50, 150, w - 50, 150)
        c.setFont("Helvetica-Oblique", 10)
        c.drawString(
            50,
            130,
            "This automated diagnostic indicates potential bottlenecks in your asset delivery pipeline.",
        )
        c.drawString(
            50,
            115,
            "SGM Audio Architect deploys containerized infrastructure to resolve latency and security gaps.",
        )

        c.save()
        print(f"      📄 Report Generated: {output_path}")
